def _longtable(colspec, header, rows, caption, label, notes=None, fontsize=None):
    L = ([r"\begingroup%s" % fontsize] if fontsize else []) + [
         r"\setlength{\tabcolsep}{3pt}" if fontsize else r"\relax",
         r"\begin{longtable}{%s}" % colspec,
         r"\caption{%s}\label{%s}\\" % (caption, label),
         r"\toprule", header + r" \\", r"\midrule", r"\endfirsthead",
         r"\multicolumn{%d}{@{}l}{\footnotesize\itshape (\Cref{%s}, continued)}\\" %
         (colspec.count("l") + colspec.count("r") + colspec.count("c"), label),
         r"\toprule", header + r" \\", r"\midrule", r"\endhead",
         r"\midrule", r"\multicolumn{%d}{r@{}}{\footnotesize\itshape (continued)}\\" %
         (colspec.count("l") + colspec.count("r") + colspec.count("c")),
         r"\endfoot", r"\bottomrule", r"\endlastfoot"]
    L += [r + r" \\" for r in rows]
    L.append(r"\end{longtable}")
    if notes:
        L.append(r"\noindent{\footnotesize %s\par}" % notes)
    if fontsize:
        L.append(r"\endgroup")
    return "\n".join(L)


def _table(colspec, header, rows, caption, label, notes=None, star=False):
    env = "table"
    L = [r"\begin{%s}[H]" % env, r"\centering",
         r"\caption{%s}\label{%s}" % (caption, label),
         r"\begin{tabular}{%s}" % colspec, r"\toprule", header + r" \\", r"\midrule"]
    L += [r + r" \\" for r in rows]
    L += [r"\bottomrule", r"\end{tabular}"]
    if notes:
        L.append(r"\par\vspace{0.6ex}{\footnotesize %s}" % notes)
    L.append(r"\end{%s}" % env)
    return "\n".join(L)


