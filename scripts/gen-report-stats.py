def sec_ladder(data):
    s = data["successor"]
    p = data.get("progenitor") or {}
    af, paf = s.get("af") or {}, p.get("af") or {}
    reg = s.get("registry") or {}
    dfs = s.get("definitions") or {}

    def cum(days):
        out, tot = [], 0
        for d in sorted(days):
            tot += days[d]
            out.append((_dnum(d), tot))
        return out

    c_succ = cum(af.get("validation_days") or {})
    c_prog = cum(paf.get("validation_days") or {})
    # extend each curve to the right edge so the step plot reads as a level, not a stop
    all_x = [x for x, _ in c_succ + c_prog]
    xmax = (max(all_x) + 2) if all_x else 1
    if c_prog:
        c_prog = c_prog + [(xmax, c_prog[-1][1])]
    if c_succ:
        c_succ = c_succ + [(xmax, c_succ[-1][1])]

    ticks, ticklabels = [], []
    d = 0
    while d <= xmax:
        ticks.append(str(d))
        ticklabels.append((CHART_ORIGIN + _dt.timedelta(days=d)).strftime("%b %d"))
        d += 7

