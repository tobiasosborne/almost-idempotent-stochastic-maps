def extract_git(repo):
    """Commit calendar + author + subject taxonomy. Snapshotted (git history is volatile)."""
    log = _git(repo, "log", "--format=%ad\x1f%an\x1f%s", "--date=short")
    if log is None:
        return None
    per_day = collections.Counter()
    authors = collections.Counter()
    subjects = collections.Counter()
    n = 0
    for line in log.splitlines():
        if not line.strip():
            continue
        parts = line.split("\x1f")
        if len(parts) != 3:
            continue
        date, author, subject = parts
        n += 1
        per_day[date] += 1
        authors[author] += 1
        # taxonomy: the token before the first ':' (the repo's de-facto commit prefix convention)
        head = subject.split(":", 1)[0].strip() if ":" in subject else subject.strip()
        subjects[head] += 1
    days = sorted(per_day)
    return {
        "commits": n,
        "first_day": days[0] if days else None,
        "last_day": days[-1] if days else None,
        "active_days": len(days),
        "per_day": {d: per_day[d] for d in days},
        "authors": _counter(authors.elements()),
        "subject_prefixes": dict(sorted(subjects.items(), key=lambda kv: (-kv[1], kv[0]))[:14]),
    }


def extract_frontier(repo):
    """The fr controller log: cycles, arms, outcomes, worker mix, decisions, evidence tiers."""
    path = pathlib.Path(repo) / ".frontier" / "log.jsonl"
    if not path.is_file():
        return None
    recs = _jsonl(path)
    per_day = collections.Counter()
    outcomes = collections.Counter()
    arms = collections.Counter()
    arm_outcome = collections.defaultdict(collections.Counter)
    arm_span = {}
    workers = collections.Counter()
    models = collections.Counter()
    roles = collections.Counter()
    decisions = collections.Counter()
    tiers = collections.Counter()
    classes = collections.Counter()
    banked_days = collections.Counter()
    legacy_outcomes = 0
    no_arm_records = 0
    no_wave_turns = 0
    t0_transitions = []
    op_discharge = None
    sharpness_xhigh = None
    stats_dispatch = None
    balloon_records = []
    restoration_records = []
    for r in recs:
        ts = r.get("ts") or ""
        d = _day(ts)
        if d:
            per_day[d] += 1
        raw_oc = r.get("outcome")
        if not raw_oc:
            oc = "unrecorded"
        elif raw_oc in KNOWN_FRONTIER_OUTCOMES:
            oc = raw_oc
        else:
            # Five legacy records put the harvest prose in `outcome` itself.  Preserve the
            # records, but do not turn arbitrary paragraphs into table columns and legends.
            oc = "legacy-free-text"
            legacy_outcomes += 1
        outcomes[oc] += 1
        arm = r.get("arm")
        if arm:
            arms[arm] += 1
            arm_outcome[arm][oc] += 1
            lo, hi = arm_span.get(arm, (ts, ts))
            arm_span[arm] = (min(lo, ts), max(hi, ts))
        else:
            no_arm_records += 1
        if oc == "orient":
            no_wave_turns += 1
        for w in (r.get("workers") or []):
            m = (w or {}).get("model") or "?"
            ro = (w or {}).get("role") or "?"
            workers["%s / %s" % (m, ro)] += 1
            models[m] += 1
            roles[ro] += 1
        dec = (r.get("decision") or {}).get("type")
        if dec:
            decisions[dec] += 1
        ev = r.get("evidence")
        if isinstance(ev, dict):
            if ev.get("tier"):
                tiers[ev["tier"]] += 1
            if ev.get("class"):
                classes[ev["class"]] += 1
        if oc == "banked" and d:
            banked_days[d] += 1

        note = r.get("note") or ""
        event_text = note or (raw_oc if oc == "legacy-free-text" else "")
        transitions = list(T0_TRANSITION_RE.finditer(event_text))
        if transitions:
            # A few session-summary records repeat an earlier start value after recording the
            # individual transition.  The last after-value is the state asserted at record end.
            m = transitions[-1]
            t0_transitions.append({
                "cycle": r.get("cycle"), "ts": ts, "day": d,
                "before": int(m.group(1)), "after": int(m.group(2)),
                "matches_in_record": len(transitions),
            })
        evidence = r.get("evidence") if isinstance(r.get("evidence"), dict) else {}
        artifact = evidence.get("artifact") or ""
        if artifact == "proofs/op-classical/export.md" and transitions:
            op_discharge = dict(t0_transitions[-1])
            op_discharge["artifact"] = artifact
        if (artifact == "proofs/lem-prh-sharpness-family-arithmetic/export.md"
                and "xhigh" in event_text.lower()):
            nm = re.search(r"(\d+)/(\d+)\s+nodes", event_text, re.I)
            cm = re.search(r"cap\s+(\d+)", event_text, re.I)
            sharpness_xhigh = {
                "cycle": r.get("cycle"), "ts": ts, "artifact": artifact,
                "nodes": int(nm.group(1)) if nm and nm.group(1) == nm.group(2) else None,
                "cap": int(cm.group(1)) if cm else None,
            }
        if "statistics layer" in event_text.lower() and "T0" in event_text:
            dm = re.search(r"T0\s*(\d+)\s*/\s*(\d+)", event_text, re.I)
            if dm:
                stats_dispatch = {"cycle": r.get("cycle"), "ts": ts,
                                  "t0": int(dm.group(1)), "registry": int(dm.group(2))}
        if re.search(r"ABORTED \[BALLOON\]|BALLOON(?:-aborted| abort| STOP)|"
                     r"ballooned at|double balloon", event_text, re.I):
            balloon_records.append({"cycle": r.get("cycle"), "ts": ts})
        if re.search(r"af-RE-VALIDATED|\bRE-FLIPPED\b", event_text):
            restoration_records.append({"cycle": r.get("cycle"), "ts": ts})
    cycles = [r.get("cycle") for r in recs if isinstance(r.get("cycle"), int)]
    days = sorted(per_day)
    t0_daily = {}
    for event in t0_transitions:
        if event["day"]:
            t0_daily[event["day"]] = event["after"]
    return {
        "records": len(recs),
        "max_cycle": max(cycles) if cycles else None,
        "first_ts": min((r.get("ts") or "" for r in recs), default=None),
        "last_ts": max((r.get("ts") or "" for r in recs), default=None),
        "active_days": len(days),
        "per_day": {d: per_day[d] for d in days},
        "banked_per_day": dict(sorted(banked_days.items())),
        "outcomes": _counter(outcomes.elements()),
        "legacy_outcome_records": legacy_outcomes,
        "no_arm_records": no_arm_records,
        "no_wave_turns": no_wave_turns,
        "arms": _counter(arms.elements()),
        "arm_outcomes": {a: _counter(arm_outcome[a].elements()) for a in sorted(arm_outcome)},
        "arm_span": {a: {"first": arm_span[a][0], "last": arm_span[a][1]} for a in sorted(arm_span)},
        "workers": _counter(workers.elements()),
        "worker_jobs": int(sum(workers.values())),
        "worker_models": _counter(models.elements()),
        "worker_roles": _counter(roles.elements()),
        "decisions": _counter(decisions.elements()),
        "evidence_tiers": _counter(tiers.elements()),
        "evidence_classes": _counter(classes.elements()),
        "t0_transitions": t0_transitions,
        "t0_daily": dict(sorted(t0_daily.items())),
        "op_classical_discharge": op_discharge,
        "sharpness_xhigh_remedy": sharpness_xhigh,
        "stats_reanalysis_dispatch": stats_dispatch,
        "balloon_record_count": len(balloon_records),
        "balloon_records": balloon_records,
        "restoration_record_count": len(restoration_records),
        "restoration_records": restoration_records,
    }


