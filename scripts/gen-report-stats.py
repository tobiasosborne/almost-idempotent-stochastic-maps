def tex(s):
    """Escape a plain string for LaTeX text mode."""
    if s is None:
        return "--"
    s = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
                 ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"),
                 ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")):
        s = s.replace(a, b)
    return s


def code(s):
    return r"\texttt{%s}" % tex(s)


def code_brk(s):
    r"""\texttt{} with an INVISIBLE break opportunity after every hyphen and slash.

    cmtt has no hyphenation, so a long identifier in prose is an unbreakable box and runs into
    the margin. \discretionary{}{}{} adds a legal break point without printing a hyphen.
    """
    return r"\texttt{%s}" % tex(s).replace("-", r"-\discretionary{}{}{}").replace(
        "/", r"/\discretionary{}{}{}")


def num(n):
    """Thousands-separated integer, LaTeX-safe."""
    if n is None:
        return "--"
    return "{:,}".format(int(n)).replace(",", r"\,")


def pct(a, b):
    return "--" if not b else "%.1f\\%%" % (100.0 * a / b)


def _dnum(day):
    """Days since the campaign origin (progenitor day 0) — the shared chart x-axis."""
    y, m, d = (int(x) for x in day.split("-"))
    return (_dt.date(y, m, d) - CHART_ORIGIN).days


