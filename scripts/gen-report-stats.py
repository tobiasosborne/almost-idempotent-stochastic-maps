def _find_sibling():
    """Locate ../almost-idempotent-positive-maps, tolerating a git worktree checkout.

    In a linked worktree ROOT.parent is the worktrees scratch dir, not the projects dir, so we also
    resolve the MAIN working tree through .git and look beside that. `AISM_PROGENITOR` overrides.
    """
    env = os.environ.get("AISM_PROGENITOR")
    cands = [pathlib.Path(env)] if env else []
    cands.append(ROOT.parent / PROGENITOR_NAME)
    dotgit = ROOT / ".git"
    if dotgit.is_file():                       # linked worktree: ".git" is a gitdir pointer file
        m = re.match(r"gitdir:\s*(.+)", dotgit.read_text(encoding="utf-8", errors="replace").strip())
        if m:
            p = pathlib.Path(m.group(1).strip())
            for parent in p.parents:           # .../<main>/.git/worktrees/<name> -> <main>
                if parent.name == ".git":
                    cands.append(parent.parent.parent / PROGENITOR_NAME)
                    break
    for c in cands:
        if c.is_dir():
            return c
    return cands[-1]


