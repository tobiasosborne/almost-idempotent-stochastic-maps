# ===================================================================== helpers

def _read(path, default=""):
    try:
        return pathlib.Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return default


def _frontmatter_field(text, field):
    m = re.search(r"^%s:\s*(.*)$" % re.escape(field), text, re.M)
    return m.group(1).strip() if m else None


def _day(ts):
    """ISO timestamp (or date) -> YYYY-MM-DD."""
    return (ts or "")[:10] or None


def _git(repo, *args):
    try:
        out = subprocess.run(["git", "-C", str(repo)] + list(args),
                             capture_output=True, text=True, check=True, timeout=120)
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout


def _counter(items):
    """Deterministic dict from a Counter: sorted by descending count, then key."""
    c = collections.Counter(items)
    return dict(sorted(c.items(), key=lambda kv: (-kv[1], str(kv[0]))))


def _listdir(path, suffix=None, exclude=()):
    p = pathlib.Path(path)
    if not p.is_dir():
        return []
    out = []
    for name in sorted(os.listdir(p)):
        if name in exclude:
            continue
        if suffix and not name.endswith(suffix):
            continue
        out.append(name)
    return out


def _jsonl(path):
    """Read valid JSON objects from a JSONL artifact, preserving file order."""
    out = []
    for line in _read(path).splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            obj = json.loads(line)
        except ValueError:
            continue
        if isinstance(obj, dict):
            out.append(obj)
    return out


def _strip_tex_comment(line):
    """Remove an unescaped TeX comment from one line."""
    out, i = [], 0
    while i < len(line):
        if line[i] == "\\" and i + 1 < len(line):
            out.append(line[i:i + 2])
            i += 2
        elif line[i] == "%":
            break
        else:
            out.append(line[i])
            i += 1
    return "".join(out)


