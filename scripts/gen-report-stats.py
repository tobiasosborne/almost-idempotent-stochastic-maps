def _write(files):
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in sorted(files.items()):
        (OUT_DIR / name).write_text(text, encoding="utf-8")


def _drift_advisory(data):
    """Cheap live-vs-snapshot comparison. Advisory only — never fails the gate."""
    snap = data.get("successor") or {}
    msgs = []
    live_fr = extract_frontier(ROOT) or {}
    if live_fr.get("records") is not None:
        d = live_fr["records"] - ((snap.get("frontier") or {}).get("records") or 0)
        if d:
            msgs.append("fr log %+d records" % d)
    live_reg = extract_registry(ROOT) or {}
    if live_reg.get("results") is not None:
        d = live_reg["results"] - ((snap.get("registry") or {}).get("results") or 0)
        if d:
            msgs.append("registry %+d results" % d)
    live_t0 = (live_reg.get("af") or {}).get("validated")
    snap_t0 = (((snap.get("registry") or {}).get("af") or {}).get("validated"))
    if live_t0 is not None and snap_t0 is not None and live_t0 != snap_t0:
        msgs.append("current T0 %+d results" % (live_t0 - snap_t0))
    live_af = extract_af(ROOT) or {}
    if live_af.get("root_validated") is not None:
        d = live_af["root_validated"] - ((snap.get("af") or {}).get("root_validated") or 0)
        if d:
            msgs.append("af roots %+d" % d)
    return msgs


def main(argv):
    args = set(argv[1:])
    unknown = args - {"--extract", "--check", "--render"}
    if unknown:
        sys.stderr.write("unknown argument(s): %s\n" % ", ".join(sorted(unknown)))
        return 2

    if "--extract" in args:
        data = do_extract()
        _write(render(data))
        print("[gen-report-stats] extracted %s and rendered %d files into %s"
              % (data["extracted_at"], len(GENERATED_TEX), OUT_DIR.relative_to(ROOT)))
        return 0

    if not EXTRACT.is_file():
        sys.stderr.write("[gen-report-stats] missing %s — run with --extract first\n"
                         % EXTRACT.relative_to(ROOT))
        return 1
    data = json.loads(_read(EXTRACT))
    files = render(data)

    if "--check" in args:
        bad = []
        for name, text in sorted(files.items()):
            path = OUT_DIR / name
            if not path.is_file():
                bad.append("%s: MISSING" % name)
            elif path.read_text(encoding="utf-8") != text:
                bad.append("%s: STALE (regenerate with python3 scripts/gen-report-stats.py)" % name)
        for m in _drift_advisory(data):
            print("[gen-report-stats] drift advisory (not an error): snapshot is behind — %s" % m)
        if bad:
            for b in bad:
                sys.stderr.write("[gen-report-stats] %s\n" % b)
            return 1
        print("[gen-report-stats] OK — %d generated files match the committed snapshot (%s)"
              % (len(files), data.get("extracted_at")))
        return 0

    _write(files)
    print("[gen-report-stats] rendered %d files from snapshot %s"
          % (len(files), data.get("extracted_at")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
