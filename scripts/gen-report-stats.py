def extract_runs(repo):
    d = pathlib.Path(repo) / "runs"
    if not d.is_dir():
        return None
    bundles = [n for n in sorted(os.listdir(d)) if (d / n).is_dir()]
    per_month = collections.Counter()
    scripts = 0
    for b in bundles:
        m = re.match(r"(\d{4}-\d{2})-\d{2}-", b)
        if m:
            per_month[m.group(1)] += 1
        sd = d / b / "scripts"
        if sd.is_dir():
            scripts += len([f for f in os.listdir(sd) if f.endswith(".py")])
    inventory_count = None
    inventory_qualified = False
    inventory_counterexamples = None
    manifest = d / "2026-07-02-ex-enumeration-rehome" / "data" / "campaign_summary.csv"
    if manifest.is_file():
        try:
            with manifest.open(encoding="utf-8", newline="") as fh:
                for row in csv.DictReader(fh):
                    if row.get("artifact_id") != "inventory_67k":
                        continue
                    m = re.match(r"(\d+)(\+?)$", row.get("instance_count") or "")
                    if m:
                        inventory_count = int(m.group(1))
                        inventory_qualified = bool(m.group(2))
                    vm = re.match(r"(\d+)_", row.get("violation_count") or "")
                    if vm:
                        inventory_counterexamples = int(vm.group(1))
                    break
        except (OSError, csv.Error):
            pass
    return {"bundles": len(bundles), "per_month": dict(sorted(per_month.items())),
            "bundle_scripts": scripts, "ids": bundles,
            "enumeration_instance_lower_bound": inventory_count,
            "enumeration_instance_qualified": inventory_qualified,
            "enumeration_counterexamples_recorded": inventory_counterexamples}


def extract_docs(repo):
    r = pathlib.Path(repo)
    out = {}
    for sub in ("plans", "waves", "audits", "lit-review", "recon", "tooling-feedback", "ingest"):
        p = r / "docs" / sub
        out[sub] = len([n for n in _listdir(p)]) if p.is_dir() else 0
    ingest_exp = r / "docs" / "ingest" / "experiments"
    out["ingest_experiment_files"] = len(_listdir(ingest_exp)) if ingest_exp.is_dir() else 0
