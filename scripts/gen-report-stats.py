#!/usr/bin/env python3
r"""
gen-report-stats.py — the CAMPAIGN-STATISTICS generated layer of the lab-book.

WHAT IT PRODUCES (all under report/generated/stats/, all generated — never hand-edit):
  campaign-extract.json  the committed DATA SNAPSHOT (the only input to rendering)
  preamble.tex           packages + the Okabe-Ito palette + pgfplots setup (\input from main.tex)
  headline.tex           the frontmatter headline block (\input right after \maketitle)
  body.tex               the section body: subsections, tables, pgfplots charts, colophon

THE STALENESS PROBLEM AND ITS SOLUTION (read this before changing anything).
  Statistics about a repo are derived from things that change on EVERY commit (git history, the
  fr controller log, the af ledgers). A naive byte-freshness gate over such a generator would be
  permanently red: the commit that lands the regenerated tables itself changes the inputs.
  So the generator is split in two, with a committed snapshot between the halves:

      EXTRACT  (explicit, human-run)   sources -> report/generated/stats/campaign-extract.json
      RENDER   (deterministic, gated)  campaign-extract.json -> *.tex

  Only RENDER is gated. `--check` re-renders from the COMMITTED extract and compares bytes, so it
  is stable across ordinary commits and fails exactly when it should: someone hand-edited a
  generated .tex, or changed the renderer without re-rendering. Refreshing the numbers is a
  deliberate act (`--extract`), documented in the section's own colophon, and the extract records
  its own `extracted_at` so the rendered section always states the as-of date in the open.

  `--check` additionally prints a non-fatal DRIFT ADVISORY comparing a handful of cheap live counts
  against the snapshot, so a badly stale snapshot is visible without being a commit-blocker.

PROGENITOR DATA (../almost-idempotent-positive-maps). Mined live during `--extract` when the sibling
  repo is present; when it is absent the previously committed progenitor block is carried forward
  unchanged (and flagged `carried_forward: true`). RENDER never touches the sibling, so the gate is
  green on machines that do not have it.

HONESTY. Every number here is a count of an artifact that exists in the repos. Nothing is modelled,
  extrapolated, or estimated unless the field name says so and the rendered text says so. LLM token
  consumption is NOT recoverable from the record; the section says so explicitly rather than
  inventing a figure.

Usage:
  python3 scripts/gen-report-stats.py --extract      # refresh the snapshot from live sources, then render
  python3 scripts/gen-report-stats.py                # render from the committed snapshot
  python3 scripts/gen-report-stats.py --check        # gate: re-render, byte-compare, drift advisory
"""

